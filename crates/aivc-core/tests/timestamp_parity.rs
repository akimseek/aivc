#[test]
fn formatting_matches_javascript_to_iso_string() {
    for (millis, expected) in GOLDEN {
        let actual = Timestamp::from_unix_millis(*millis);
        assert_eq!(
            actual.as_str(),
            *expected,
            "毫秒 {millis} 的格式化结果与 Node toISOString() 不一致"
        );
    }
}

#[test]
fn parsing_round_trips_every_golden_value() {
    for (millis, iso) in GOLDEN {
        let parsed = Timestamp::from_raw(*iso)
            .to_unix_millis()
            .unwrap_or_else(|| panic!("无法解析 {iso}"));
        assert_eq!(parsed, *millis, "{iso} 解析结果不正确");
    }
}

#[test]
fn every_golden_value_has_exactly_three_fractional_digits() {
    // 这是与 RFC 3339 实现的关键差异点：整秒也必须补足 .000。
    for (_, iso) in GOLDEN {
        let dot = iso.find('.').expect("必须包含毫秒分隔符");
        assert_eq!(
            iso.len() - dot,
            5,
            "{iso} 的小数部分不是固定 3 位（RFC 3339 实现会裁剪尾随零）"
        );
        assert!(iso.ends_with('Z'), "{iso} 必须以 Z 结尾");
    }
}

#[test]
fn parsing_accepts_values_without_fractional_seconds() {
    // 各 CLI 写入的时间戳可能不带毫秒，需要能解析且不丢秒。
    for (millis, iso) in GOLDEN {
        let without_fraction = format!("{}Z", &iso[..19]);
        let parsed = Timestamp::from_raw(&without_fraction)
            .to_unix_millis()
            .unwrap_or_else(|| panic!("无法解析 {without_fraction}"));
        // 截断毫秒后应当恰好落在整秒边界上。
        assert_eq!(
            parsed,
            millis - millis.rem_euclid(1000),
            "{without_fraction} 解析结果不正确"
        );
    }
}
