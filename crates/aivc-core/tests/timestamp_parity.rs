//! 时间戳与 JavaScript `Date.prototype.toISOString()` 的对拍测试。
//!
//! # 为什么需要这个测试
//!
//! 时间戳字符串会落库、进 JSON 契约并被渲染层展示。现网全部时间戳来自
//! `toISOString()`，其格式恒为「UTC + 固定 3 位毫秒」。Rust 生态常见的
//! RFC 3339 实现会裁剪尾随零（`…:01Z` 而非 `…:01.000Z`），一旦采用就会造成
//! 肉眼可见的格式漂移与字符串比较失配。
//!
//! 下面的黄金数据由 Node 24 生成：
//!
//! ```js
//! for (const v of values) console.log(`${v}|${new Date(v).toISOString()}`);
//! ```
//!
//! 数据是**静态固化**的，因此运行测试不需要 Node。若要扩充，请用上面的脚本
//! 重新生成并整体替换，不要手工编辑单条。

