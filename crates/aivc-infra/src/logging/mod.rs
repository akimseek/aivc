//! 日志初始化与轮转。
//!
//! 统一日志出口：`tracing` 订阅器 + 按大小轮转的文件写入。**绝不记录** API Key、
//! 请求/响应正文、终端输出与会话正文——这是功能一致与安全契约的一部分。
//!
//! 对应现网 `core/performance.ts`（启动阶段埋点）。
//!
//! # 网关的日志**不在这里**
//!
//! 旧工程另有一份 `logs/gateway.log`（+ 轮转 `.1`，单文件 2 MB），与数据库里的
//! 请求记录并存，界面上那个「仅文件日志 / 仅请求记录 / 两者」的下拉就是为区分
//! 它们而存在的。
//!
//! 本工程**不写那份文本日志**：它的内容与请求记录完全重合，而请求记录可查询
//! （过滤、分页、聚合用量）。网关日志唯一的去处是数据库，
//! 详见 [`crate::config::paths`] 的模块说明。
